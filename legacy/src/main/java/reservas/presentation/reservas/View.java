    private void cargarHoras(JComboBox<String> combo) {

        combo.removeAllItems();

        for (int hora = 6; hora <= 22; hora++) {

            combo.addItem(
                    String.format(
                            "%02d:00",
                            hora
                    )
            );
        }
    }

    private void ponerIcono(
            JButton boton,
            String ruta
    ) {

        URL url = getClass().getResource(ruta);

        if (url != null) {

            boton.setIcon(
                    new ImageIcon(url)
            );

        } else {

            System.out.println(
                    "No se encontró el icono: " + ruta
            );
        }
    }

